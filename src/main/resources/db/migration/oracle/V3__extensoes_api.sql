--                              região mais próxima do GPS do relato
--   IDEMPOTENCIA               respostas guardadas de POST /relatos com Idempotency-Key
-- Não altera nada do que o repositório database usa: as colunas novas são opcionais
-- e a tabela nova não tem gatilhos. Reexecutável.
-- =============================================================================
DECLARE
  PROCEDURE criar(p_ddl IN VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_ddl;
  EXCEPTION
    WHEN OTHERS THEN
      -- -1430: coluna já existe · -955: nome já usado · -1408: índice já existe
      IF SQLCODE NOT IN (-1430, -955, -1408, -2261, -2275) THEN
        RAISE;
      END IF;
  END criar;
BEGIN
  criar('ALTER TABLE regiao ADD (latitude NUMBER(9,6), longitude NUMBER(9,6))');

  -- ON DELETE CASCADE: o 06_seed.sql do repositório database faz DELETE FROM usuario.
  criar('
    CREATE TABLE idempotencia (
      id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
      usuario_id      NUMBER        NOT NULL,
      chave           VARCHAR2(100) NOT NULL,
      hash_requisicao VARCHAR2(64)  NOT NULL,
      status_http     NUMBER(3)     NOT NULL,
      corpo_resposta  NCLOB         NOT NULL,
      criado_em       DATE          DEFAULT SYSDATE NOT NULL,
      CONSTRAINT pk_idempotencia               PRIMARY KEY (id),
      CONSTRAINT uk_idempotencia_usuario_chave UNIQUE (usuario_id, chave),
      CONSTRAINT fk_idempotencia_usuario       FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE
    )');
  criar('CREATE INDEX ix_idempotencia_criado ON idempotencia (criado_em)');
END;
/

