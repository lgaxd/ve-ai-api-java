-- =============================================================================
-- Vê AI · Oracle · V1 · Schema do domínio
-- Mesmas 8 tabelas + AUDITORIA_RELATO do repositório database (oracle/01_ddl.sql),
-- com os mesmos nomes, tipos, constraints e índices.
--
-- Diferença: NÃO apaga nada. Cada objeto só é criado se ainda não existir, então esta
-- migração funciona tanto num schema vazio (Oracle do docker-compose) quanto num schema
-- da FIAP onde o 00_instalar.sql do repositório database já foi executado.
-- =============================================================================
DECLARE
  v_qtd PLS_INTEGER;

  -- Ignora só "objeto já existe" (tabela, índice, PK, UK, FK); qualquer outro erro sobe.
  PROCEDURE criar(p_ddl IN VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_ddl;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE NOT IN (-955, -1408, -2260, -2261, -2275) THEN
        RAISE;
      END IF;
  END criar;
BEGIN
  -- Proteção: se já existe uma tabela USUARIO que não é a do Vê AI (outro projeto no
  -- mesmo usuário da FIAP), para aqui com uma mensagem clara em vez de corromper dados.
  SELECT COUNT(*) INTO v_qtd FROM user_tables WHERE table_name = 'USUARIO';
  IF v_qtd = 1 THEN
    SELECT COUNT(*) INTO v_qtd
      FROM user_tab_columns
     WHERE table_name = 'USUARIO' AND column_name = 'PERGUNTA_LIVRE_ATIVA';
    IF v_qtd = 0 THEN
      RAISE_APPLICATION_ERROR(-20100,
        'Já existe uma tabela USUARIO de outro projeto neste schema. Use um schema/usuário só para o Vê AI.');
    END IF;
  END IF;

  criar('
    CREATE TABLE usuario (
      id                   NUMBER GENERATED BY DEFAULT AS IDENTITY,
      nome                 VARCHAR2(120) NOT NULL,
      email                VARCHAR2(160) NOT NULL,
      senha_hash           VARCHAR2(100) NOT NULL,
      papel                VARCHAR2(10)  NOT NULL,
      velocidade_voz       NUMBER(3,2)   DEFAULT 1 NOT NULL,
      pergunta_livre_ativa NUMBER(1)     DEFAULT 0 NOT NULL,
      criado_em            DATE          DEFAULT SYSDATE NOT NULL,
      CONSTRAINT pk_usuario          PRIMARY KEY (id),
      CONSTRAINT uk_usuario_email    UNIQUE (email),
      CONSTRAINT ck_usuario_papel    CHECK (papel IN (''CIDADAO'', ''GESTOR'')),
      CONSTRAINT ck_usuario_voz      CHECK (velocidade_voz BETWEEN 0.5 AND 2),
      CONSTRAINT ck_usuario_pergunta CHECK (pergunta_livre_ativa IN (0, 1))
    )');

  criar('
    CREATE TABLE regiao (
      id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
      nome   VARCHAR2(80) NOT NULL,
      cidade VARCHAR2(80) NOT NULL,
      uf     CHAR(2)      NOT NULL,
      CONSTRAINT pk_regiao      PRIMARY KEY (id),
      CONSTRAINT uk_regiao_nome UNIQUE (nome, cidade, uf)
    )');

  criar('
    CREATE TABLE gestor_regiao (
      gestor_id NUMBER NOT NULL,
      regiao_id NUMBER NOT NULL,
      CONSTRAINT pk_gestor_regiao        PRIMARY KEY (gestor_id, regiao_id),
      CONSTRAINT fk_gestor_regiao_gestor FOREIGN KEY (gestor_id) REFERENCES usuario (id),
      CONSTRAINT fk_gestor_regiao_regiao FOREIGN KEY (regiao_id) REFERENCES regiao (id)
    )');

  criar('
    CREATE TABLE descricao (
      id                 NUMBER GENERATED BY DEFAULT AS IDENTITY,
      usuario_id         NUMBER        NOT NULL,
      modo               VARCHAR2(10)  NOT NULL,
      resumo             VARCHAR2(500) NOT NULL,
      descricao_completa CLOB,
      perigos            CLOB          DEFAULT ''[]'' NOT NULL,
      objetos            CLOB          DEFAULT ''[]'' NOT NULL,
      barreira_detectada NUMBER(1)     DEFAULT 0 NOT NULL,
      barreira_tipo      VARCHAR2(30),
      latencia_ms        NUMBER(6)     NOT NULL,
      util               NUMBER(1),
      criado_em          DATE          DEFAULT SYSDATE NOT NULL,
      CONSTRAINT pk_descricao          PRIMARY KEY (id),
      CONSTRAINT fk_descricao_usuario  FOREIGN KEY (usuario_id) REFERENCES usuario (id),
      CONSTRAINT ck_descricao_modo     CHECK (modo IN (''AMBIENTE'', ''TEXTO'')),
      CONSTRAINT ck_descricao_perigos  CHECK (perigos IS JSON),
      CONSTRAINT ck_descricao_objetos  CHECK (objetos IS JSON),
      CONSTRAINT ck_descricao_barreira CHECK (barreira_detectada IN (0, 1)),
      CONSTRAINT ck_descricao_tipo     CHECK (barreira_tipo IN (''CALCADA_DANIFICADA'', ''OBSTRUCAO_PERMANENTE'',
                                              ''PISO_TATIL'', ''RAMPA'', ''SEMAFORO_SEM_SOM'',
                                              ''OBRA_SEM_SINALIZACAO'', ''OUTRO'')),
      CONSTRAINT ck_descricao_tipo_req CHECK (barreira_detectada = 0 OR barreira_tipo IS NOT NULL),
      CONSTRAINT ck_descricao_latencia CHECK (latencia_ms >= 0),
      CONSTRAINT ck_descricao_util     CHECK (util IN (0, 1))
    )');

  criar('
    CREATE TABLE relato (
      id               NUMBER GENERATED BY DEFAULT AS IDENTITY,
      cidadao_id       NUMBER         NOT NULL,
      descricao_id     NUMBER,
      regiao_id        NUMBER         NOT NULL,
      tipo             VARCHAR2(30)   NOT NULL,
      gravidade        VARCHAR2(5)    NOT NULL,
      texto            VARCHAR2(1000) NOT NULL,
      latitude         NUMBER(9,6)    NOT NULL,
      longitude        NUMBER(9,6)    NOT NULL,
      endereco         VARCHAR2(200),
      status           VARCHAR2(12)   DEFAULT ''ABERTO'' NOT NULL,
      protocolo_orgao  VARCHAR2(40),
      motivo_descarte  VARCHAR2(300),
      total_apoios     NUMBER(6)      DEFAULT 0 NOT NULL,
      prioridade       NUMBER(10,2)   DEFAULT 0 NOT NULL,
      norma_referencia VARCHAR2(200),
      criado_em        DATE           DEFAULT SYSDATE NOT NULL,
      atualizado_em    DATE           DEFAULT SYSDATE NOT NULL,
      CONSTRAINT pk_relato            PRIMARY KEY (id),
      CONSTRAINT fk_relato_cidadao    FOREIGN KEY (cidadao_id)   REFERENCES usuario (id),
      CONSTRAINT fk_relato_descricao  FOREIGN KEY (descricao_id) REFERENCES descricao (id) ON DELETE SET NULL,
      CONSTRAINT fk_relato_regiao     FOREIGN KEY (regiao_id)    REFERENCES regiao (id),
      CONSTRAINT ck_relato_tipo       CHECK (tipo IN (''CALCADA_DANIFICADA'', ''OBSTRUCAO_PERMANENTE'',
                                             ''PISO_TATIL'', ''RAMPA'', ''SEMAFORO_SEM_SOM'',
                                             ''OBRA_SEM_SINALIZACAO'', ''OUTRO'')),
      CONSTRAINT ck_relato_gravidade  CHECK (gravidade IN (''BAIXA'', ''MEDIA'', ''ALTA'')),
      CONSTRAINT ck_relato_status     CHECK (status IN (''ABERTO'', ''EM_TRIAGEM'', ''ENCAMINHADO'',
                                             ''RESOLVIDO'', ''DESCARTADO'')),
      CONSTRAINT ck_relato_latitude   CHECK (latitude BETWEEN -90 AND 90),
      CONSTRAINT ck_relato_longitude  CHECK (longitude BETWEEN -180 AND 180),
      CONSTRAINT ck_relato_apoios     CHECK (total_apoios >= 0),
      CONSTRAINT ck_relato_protocolo  CHECK (status NOT IN (''ENCAMINHADO'', ''RESOLVIDO'') OR protocolo_orgao IS NOT NULL),
      CONSTRAINT ck_relato_motivo     CHECK (status <> ''DESCARTADO'' OR motivo_descarte IS NOT NULL)
    )');

  -- Sem ON DELETE CASCADE de propósito (ver 01_ddl.sql): o trg_conta_apoio atualiza RELATO.
  criar('
    CREATE TABLE apoio_relato (
      id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
      relato_id  NUMBER NOT NULL,
      usuario_id NUMBER NOT NULL,
      criado_em  DATE   DEFAULT SYSDATE NOT NULL,
      CONSTRAINT pk_apoio_relato         PRIMARY KEY (id),
      CONSTRAINT fk_apoio_relato_relato  FOREIGN KEY (relato_id)  REFERENCES relato (id),
      CONSTRAINT fk_apoio_relato_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
      CONSTRAINT uk_apoio_relato         UNIQUE (relato_id, usuario_id)
    )');

  criar('
    CREATE TABLE atualizacao_relato (
      id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
      relato_id       NUMBER       NOT NULL,
      gestor_id       NUMBER       NOT NULL,
      status_anterior VARCHAR2(12) NOT NULL,
      status_novo     VARCHAR2(12) NOT NULL,
      comentario      VARCHAR2(500),
      criado_em       DATE         DEFAULT SYSDATE NOT NULL,
      CONSTRAINT pk_atualizacao_relato  PRIMARY KEY (id),
      CONSTRAINT fk_atualizacao_relato  FOREIGN KEY (relato_id) REFERENCES relato (id) ON DELETE CASCADE,
      CONSTRAINT fk_atualizacao_gestor  FOREIGN KEY (gestor_id) REFERENCES usuario (id),
      CONSTRAINT ck_atualizacao_ant     CHECK (status_anterior IN (''ABERTO'', ''EM_TRIAGEM'', ''ENCAMINHADO'',
                                               ''RESOLVIDO'', ''DESCARTADO'')),
      CONSTRAINT ck_atualizacao_novo    CHECK (status_novo IN (''ABERTO'', ''EM_TRIAGEM'', ''ENCAMINHADO'',
                                               ''RESOLVIDO'', ''DESCARTADO''))
    )');

  criar('
    CREATE TABLE notificacao (
      id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
      usuario_id NUMBER        NOT NULL,
      relato_id  NUMBER        NOT NULL,
      mensagem   VARCHAR2(300) NOT NULL,
      lida       NUMBER(1)     DEFAULT 0 NOT NULL,
      criado_em  DATE          DEFAULT SYSDATE NOT NULL,
      CONSTRAINT pk_notificacao         PRIMARY KEY (id),
      CONSTRAINT fk_notificacao_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
      CONSTRAINT fk_notificacao_relato  FOREIGN KEY (relato_id)  REFERENCES relato (id) ON DELETE CASCADE,
      CONSTRAINT ck_notificacao_lida    CHECK (lida IN (0, 1))
    )');

  criar('
    CREATE TABLE auditoria_relato (
      id                NUMBER GENERATED BY DEFAULT AS IDENTITY,
      relato_id         NUMBER        NOT NULL,
      operacao          VARCHAR2(6)   NOT NULL,
      usuario_bd        VARCHAR2(128) NOT NULL,
      data_operacao     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
      status_antigo     VARCHAR2(12),
      status_novo       VARCHAR2(12),
      prioridade_antiga NUMBER(10,2),
      prioridade_nova   NUMBER(10,2),
      CONSTRAINT pk_auditoria_relato PRIMARY KEY (id),
      CONSTRAINT ck_auditoria_op     CHECK (operacao IN (''INSERT'', ''UPDATE'', ''DELETE''))
    )');

  criar('CREATE INDEX ix_gestor_regiao_regiao ON gestor_regiao (regiao_id)');
  criar('CREATE INDEX ix_descricao_usuario    ON descricao (usuario_id, criado_em)');
  criar('CREATE INDEX ix_relato_cidadao       ON relato (cidadao_id)');
  criar('CREATE INDEX ix_relato_descricao     ON relato (descricao_id)');
  criar('CREATE INDEX ix_relato_regiao_status ON relato (regiao_id, status, prioridade)');
  criar('CREATE INDEX ix_relato_tipo_geo      ON relato (tipo, status, latitude, longitude)');
  criar('CREATE INDEX ix_apoio_usuario        ON apoio_relato (usuario_id)');
  criar('CREATE INDEX ix_atualizacao_relato   ON atualizacao_relato (relato_id)');
  criar('CREATE INDEX ix_atualizacao_gestor   ON atualizacao_relato (gestor_id)');
  criar('CREATE INDEX ix_notificacao_usuario  ON notificacao (usuario_id, lida)');
  criar('CREATE INDEX ix_notificacao_relato   ON notificacao (relato_id)');
  criar('CREATE INDEX ix_auditoria_relato     ON auditoria_relato (relato_id, data_operacao)');
END;
/

COMMENT ON TABLE usuario            IS 'Cidadão com deficiência visual ou gestor da rede de apoio (ONG/CRAS)';
COMMENT ON TABLE regiao             IS 'Bairro ou subprefeitura atendida pela rede de apoio';
COMMENT ON TABLE gestor_regiao      IS 'Regiões sob responsabilidade de cada gestor';
COMMENT ON TABLE descricao          IS 'Descrição do ambiente gerada pela IA (a imagem nunca é armazenada)';
COMMENT ON TABLE relato             IS 'Barreira de acessibilidade relatada à rede de apoio';
COMMENT ON TABLE apoio_relato       IS 'Apoio (+1) de outro cidadão a um relato existente a até 30 m';
COMMENT ON TABLE atualizacao_relato IS 'Histórico de mudanças de status feitas pelo gestor';
COMMENT ON TABLE notificacao        IS 'Avisos lidos em voz alta pelo app';
COMMENT ON TABLE auditoria_relato   IS 'Auditoria técnica de INSERT/UPDATE/DELETE em RELATO';
COMMENT ON COLUMN relato.prioridade IS 'peso da gravidade (1/3/5) x (1 + total_apoios) + dias em aberto; 0 se finalizado';
COMMENT ON COLUMN descricao.util    IS '1 = útil, 0 = não útil, NULL = não avaliada';
